/* 关于「显示逻辑放在哪」的说明（用户不需要改任何东西）
 *
 * 显示区域的取图由 env\simu_env.c 里的 SCUT_OutImageRow() 负责：
 * 它按 (SCUT_OUT_IMAGE_Y, SCUT_OUT_IMAGE_X) 定位到 ROI 左上角，
 * 再按真实的行步长 SCUT_IMAGE_W 逐行取，显示层调它即可。
 *
 * ★ 行步长必须是 SCUT_IMAGE_W（整幅宽度），不能是 SCUT_OUT_IMAGE_W。
 *   输出数组是整幅大小的二维数组，ROI 只是上面开的一个「窗口」，
 *   行与行并不连续。用 ROI 宽度当步长会从第 1 行起就定位错，
 *   画面错位、写入越界（且不一定崩，很难查）。
 *
 * 历史说明：早期版本把这块逻辑（SCUT_OUT_IMAGE_PTR）定义在 code\camera.c 里，
 *           导致仿真环境的显示逻辑混进了用户算法文件，算法没法直接搬到
 *           单片机。现已全部移到 env\ 与 config.h。 */

