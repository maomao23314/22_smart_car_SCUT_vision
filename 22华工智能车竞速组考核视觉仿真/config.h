/*********************************************************************************************************************
* 摄像头图像尺寸
*
* 说明：MT9V03X 常见分辨率就是 188x120。
*       code\ 里的算法统一用 SCUT_IMAGE_W / SCUT_IMAGE_H，不写死数字，
*       所以换摄像头（例如 160x120）时只改这里两行即可。
*
* 注意：改完要保证 pic\ 里的测试图尺寸与之一致，否则图像会被裁切或留黑。
********************************************************************************************************************/
#define SCUT_IMAGE_W                (188)                                       // 摄像头图像宽度
#define SCUT_IMAGE_H                (120)                                       // 摄像头图像高度

/*********************************************************************************************************************
* 要显示的图像
*
* 说明：环境会把「输出图像」显示在窗口右侧，标题是「处理后的图像」。
*       输出图像【不在 code\ 里定义】，而是由下面几项在这里配置：
*
*           SCUT_OUT_IMAGE_ARRAY    要显示的数组（会自动定义成 uint8 a[H][W]）
*           SCUT_OUT_IMAGE_W / H    显示区域宽 / 高（可以小于整幅图）
*           SCUT_OUT_IMAGE_X / Y    显示起始列 / 行（做 ROI 显示时用）
*
*       环境会按 SCUT_OUT_IMAGE_W/H/X/Y 自动从数组上切一块来显示，
*       窗口尺寸也随之调整。所以想换输出图像或只看一块 ROI，
*       只改本文件即可，不用动 code\ 里的任何代码。
*
*       算法里用 SCUT_OutImageSet(x, y, v) 写像素，坐标相对显示区域，
*       不需要自己算 ROI 偏移。
*
* 为什么这样设计：
*       code\ 下的算法要能直接拷到 CH32 车载工程里编译，
*       所以「输出到哪个数组、显示多大」这类仿真环境的事不该写死在算法里，
*       统一收到本文件，算法只引用 SCUT_OUT_IMAGE_W/H 这些宏。
*
* 约束：X + W 不能超过 SCUT_IMAGE_W，Y + H 不能超过 SCUT_IMAGE_H。
*       超了会在编译期直接报错（环境里放了静态断言），不会留到运行时。
********************************************************************************************************************/
#define SCUT_OUT_IMAGE_ARRAY        output_image                                // 要显示的图像数组名
#define SCUT_OUT_IMAGE_ARRAY_TYPE   uint8                                       // 数组元素类型（灰度图就是 uint8）

#define SCUT_OUT_IMAGE_W            SCUT_IMAGE_W                                // 显示区域宽度 可以小于 188
#define SCUT_OUT_IMAGE_H            SCUT_IMAGE_H                                // 显示区域高度 可以小于 120
#define SCUT_OUT_IMAGE_X            0                                           // 显示起始列（做 ROI 显示时用）
#define SCUT_OUT_IMAGE_Y            0                                           // 显示起始行（做 ROI 显示时用）

/*********************************************************************************************************************
* 测试图片
* 说明：图片按 SCUT_PIC_DIR/<图片号>SCUT_PIC_EXT 读取，例如 pic/1/3.bmp。
*       图片号必须从 1 开始连续编号，环境靠文件名统计每组有多少张。
*       SCUT_PIC_DIR 指向「起始图集」，末级是数字时可以用 +/- 前后换组。
********************************************************************************************************************/
#define SCUT_PIC_DIR                "pic/1"                                     // 起始图集文件夹 末尾不要加斜杠
#define SCUT_PIC_EXT                ".bmp"                                      // 图片后缀 也可以写 ".png"

/*********************************************************************************************************************
* 图像处理重复次数
* 说明：每帧调用 image_process() 的次数。
*       按 R 键会临时改成 1000 次做复杂度测试，显示的是「平均每次」的微秒数，
*       所以按 R 前后显示的数字可以直接对比。
********************************************************************************************************************/
#define SCUT_PROCESS_REPEAT         (1)                                         // 每帧重复调用次数

/*********************************************************************************************************************
* 窗口
* 说明：窗口坐标按自己显示器情况调整；缩放系数越大图越清楚，但窗口也越大。
********************************************************************************************************************/
#define SCUT_WINDOW_X               (200)                                       // 窗口左上角横坐标
#define SCUT_WINDOW_Y               (60)                                        // 窗口左上角纵坐标
#define SCUT_WINDOW_SCALE           (3.0f)                                      // 默认缩放系数 可实时用 Ctrl+/- 调

/*********************************************************************************************************************
* 日志显示
* 说明：SCUT_Log 输出的行数超过窗口剩余高度时，窗口会自动向下加高。
********************************************************************************************************************/
#define SCUT_LOG_MAX_LINES          (40)                                        // 日志区最多支持多少行

/*********************************************************************************************************************
* 热重载（与图像编辑器联动）
* 说明：打开后，环境会监测「当前正在显示的那张图片」是否被外部程序改写。
*       你在图像编辑器里调好光照另存为同一路径，仿真环境会自动重新读图并重跑算法，
*       不需要手动按 +/- 翻页。运行中随时可按 H 键开关。
*       监测的是当前图片本身，所以你翻到哪张就盯哪张，不用额外指定目录。
********************************************************************************************************************/
#define SCUT_HOT_RELOAD             (1)                                         // 1=开启热重载 0=关闭
#define SCUT_HOT_RELOAD_COOLDOWN_MS (300)                                       // 两次重载最小间隔(毫秒)
                                                                                // 算法很慢时调大 避免刷新堆积

/*===================================================================================================================
*                                       环境底层参数（一般不用改）
*==================================================================================================================*/

#define SCUT_USE_CONSOLE            (1)                                         // 1=保留控制台窗口 能看到 printf 诊断信息
                                                                                // 0=只显示图形窗口 发布时可以改 0

/* 关于「显示逻辑放在哪」的说明（用户不需要改任何东西）
 *
 * 显示区域的取图由 env\simu_env.c 里的 SCUT_OutImageRow() 负责：
 * 它按 (SCUT_OUT_IMAGE_Y, SCUT_OUT_IMAGE_X) 定位到 ROI 左上角，
 * 再按真实的行步长 SCUT_IMAGE_W 逐行取，显示层调它即可。
 *
 * ★ 行步长必须是 SCUT_IMAGE_W（整幅宽度），不能是 SCUT_OUT_IMAGE_W。
 *   输出数组是整幅大小的二维数组，ROI 只是上面开的一个「窗口」，
 *   行与行并不连续。用 ROI 宽度当步长会从第 1 行起就定位错，
 *   画面错位、写入越界（且不一定崩，很难查）。
 *
 * 历史说明：早期版本把这块逻辑（SCUT_OUT_IMAGE_PTR）定义在 code\camera.c 里，
 *           导致仿真环境的显示逻辑混进了用户算法文件，算法没法直接搬到
 *           单片机。现已全部移到 env\ 与 config.h。 */

#endif
