/*********************************************************************************************************************
* 摄像头图像尺寸
*
* 说明：MT9V03X 常见分辨率就是 188x120。
*       code\ 里的算法统一用 SCUT_IMAGE_W / SCUT_IMAGE_H，不写死数字，
*       所以换摄像头（例如 160x120）时只改这里两行即可。
*
* 注意：改完要保证 pic\ 里的测试图尺寸与之一致，否则图像会被裁切或留黑。
********************************************************************************************************************/
#define SCUT_IMAGE_W                (188)                                       // 摄像头图像宽度
#define SCUT_IMAGE_H                (120)                                       // 摄像头图像高度

/*********************************************************************************************************************
* 要显示的图像
*
* 说明：环境会把「输出图像」显示在窗口右侧，标题是「处理后的图像」。
*       输出图像【不在 code\ 里定义】，而是由下面几项在这里配置：
*
*           SCUT_OUT_IMAGE_ARRAY    要显示的数组（会自动定义成 uint8 a[H][W]）
*           SCUT_OUT_IMAGE_W / H    显示区域宽 / 高（可以小于整幅图）
*           SCUT_OUT_IMAGE_X / Y    显示起始列 / 行（做 ROI 显示时用）
*
*       环境会按 SCUT_OUT_IMAGE_W/H/X/Y 自动从数组上切一块来显示，
*       窗口尺寸也随之调整。所以想换输出图像或只看一块 ROI，
*       只改本文件即可，不用动 code\ 里的任何代码。
*
*       算法里用 SCUT_OutImageSet(x, y, v) 写像素，坐标相对显示区域，
*       不需要自己算 ROI 偏移。
*
* 为什么这样设计：
*       code\ 下的算法要能直接拷到 CH32 车载工程里编译，
*       所以「输出到哪个数组、显示多大」这类仿真环境的事不该写死在算法里，
*       统一收到本文件，算法只引用 SCUT_OUT_IMAGE_W/H 这些宏。
*
* 约束：X + W 不能超过 SCUT_IMAGE_W，Y + H 不能超过 SCUT_IMAGE_H。
*       超了会在编译期直接报错（环境里放了静态断言），不会留到运行时。
********************************************************************************************************************/
#define SCUT_OUT_IMAGE_ARRAY        output_image                                // 要显示的图像数组名
#define SCUT_OUT_IMAGE_ARRAY_TYPE   uint8                                       // 数组元素类型（灰度图就是 uint8）

#define SCUT_OUT_IMAGE_W            SCUT_IMAGE_W                                // 显示区域宽度 可以小于 188
#define SCUT_OUT_IMAGE_H            SCUT_IMAGE_H                                // 显示区域高度 可以小于 120
#define SCUT_OUT_IMAGE_X            0                                           // 显示起始列（做 ROI 显示时用）
#define SCUT_OUT_IMAGE_Y            0                                           // 显示起始行（做 ROI 显示时用）

/* ★ 上面四行的【写法】要和 code\scut_port.h 里的兜底定义保持逐字一致
 *   （X / Y 写成裸的 0，不要加括号写成 (0)）。
 *   原因：code\ 下的算法可能先于本文件被包含，那时 scut_port.h 会给出
 *   一份兜底定义。两份定义逐字相同时，按 C 标准属于「相同重定义」，
 *   合法且不报警告；一旦写法不同（(0) vs 0），就会报
 *       warning: "SCUT_OUT_IMAGE_X" redefined
 *   值是等价的，但警告会淹没真正的告警。改这里时请一并留意。 */

/*********************************************************************************************************************
* 测试图片
* 说明：图片按 SCUT_PIC_DIR/<图片号>SCUT_PIC_EXT 读取，例如 pic/1/3.bmp。
*       图片号必须从 1 开始连续编号（从 1 开始，不要从 0 开始），
*       环境靠文件名统计每组有多少张。
*       SCUT_PIC_DIR 指向「起始图集」，末级是数字时可以用 +/- 前后换组。
*
* ★ 格式支持（不用改代码就能换格式）
*   读图是按【文件内容】判断格式的，不看后缀，所以下面这些都能直接读：
*       .bmp  .png  .jpg  .jpeg  .gif  .tif  .tiff  .emf  .wmf
*   你只要把 SCUT_PIC_EXT 写成对应的后缀即可。
*   甚至同一组里混着放 bmp 和 png 也没问题。
*
* ★ 也可以一次配多个后缀（用逗号分隔，按顺序优先匹配）：
*       #define SCUT_PIC_EXT   ".bmp,.png"
*   适合"换了一批图但后缀不一样"或者"图集里格式混着"的情况。
*   写了不带点的形式（bmp,png）也会自动补点，两种写法都可以。
********************************************************************************************************************/
#define SCUT_PIC_DIR                "pic/1"                                     // 起始图集文件夹 末尾不要加斜杠
#define SCUT_PIC_EXT                ".bmp"                                      // 图片后缀 也可写 ".png" 或 ".bmp,.png"

/*********************************************************************************************************************
* 图像处理重复次数
* 说明：每帧调用 image_process() 的次数。
*       按 R 键会临时改成 1000 次做复杂度测试，显示的是「平均每次」的微秒数，
*       所以按 R 前后显示的数字可以直接对比。
********************************************************************************************************************/
#define SCUT_PROCESS_REPEAT         (1)                                         // 每帧重复调用次数

/*********************************************************************************************************************
* 窗口
* 说明：窗口坐标按自己显示器情况调整；缩放系数越大图越清楚，但窗口也越大。
********************************************************************************************************************/
#define SCUT_WINDOW_X               (200)                                       // 窗口左上角横坐标
#define SCUT_WINDOW_Y               (60)                                        // 窗口左上角纵坐标
#define SCUT_WINDOW_SCALE           (3.0f)                                      // 默认缩放系数 可实时用 Ctrl+/- 调

/*********************************************************************************************************************
* 日志显示
* 说明：SCUT_Log 输出的行数超过窗口剩余高度时，窗口会自动向下加高。
********************************************************************************************************************/
#define SCUT_LOG_MAX_LINES          (40)                                        // 日志区最多支持多少行

/*********************************************************************************************************************
* 热重载（与图像编辑器联动）
* 说明：打开后，环境会监测「当前正在显示的那张图片」是否被外部程序改写。
*       你在图像编辑器里调好光照另存为同一路径，仿真环境会自动重新读图并重跑算法，
*       不需要手动按 +/- 翻页。运行中随时可按 H 键开关。
*       监测的是当前图片本身，所以你翻到哪张就盯哪张，不用额外指定目录。
********************************************************************************************************************/
#define SCUT_HOT_RELOAD             (1)                                         // 1=开启热重载 0=关闭
#define SCUT_HOT_RELOAD_COOLDOWN_MS (300)                                       // 两次重载最小间隔(毫秒)
                                                                                // 算法很慢时调大 避免刷新堆积

/*********************************************************************************************************************
* 用户算法入口（★ 通常不用改）
*
* 说明：环境调用的两个入口函数名【默认】是
*           void image_init (void)     开机初始化，在所有帧开始之前调一次
*           int  image_process (void)  每帧的图像处理主函数，环境自动调用并计时
*
*       如果你的算法里这两个函数叫别的名字（比如 my_vision_init / my_vision_run），
*       在下面把宏改成你的函数名即可，环境会自动按新名字调用，算法文件一个字不用动。
*
* 为什么要做成宏：
*       环境（main.cpp 与 env\disp_env.cpp）是"不知道"你算法内部命名的，
*       直接写死函数名就等于强迫所有人必须用这两个名字。
*       改成宏之后，命名权交回算法作者，环境只认配置。
*
* 注意：
*       1) 签名必须一致 —— 初始化是 void f(void)，处理是 int f(void)。
*       2) 逆透视这类"只需要建一次表"的工作，放初始化函数里最合适：
*          它不在计时区间内，不会被算进"处理时间"。
*       3) 初始化函数在环境窗口建好之后、第一帧之前调用（顺序见 main.cpp），
*          所以里面可以安全地调用 SCUT_Log 打日志。
********************************************************************************************************************/
#define SCUT_USER_INIT_FUNC         image_init                                  // 你的开机初始化函数名
#define SCUT_USER_PROCESS_FUNC      image_process                               // 你的每帧处理函数名

/*********************************************************************************************************************
* 是否启用逆透视（透视变换）初始化
*
* 说明：逆透视要先算出"俯视图每个像素对应原图哪个像素"的映射表。
*       这张表只需要建一次，之后每帧直接用 —— 所以建表放在初始化里，
*       不占用"处理时间"。
*
*       本开关决定环境要不要帮你调这个建表函数：
*           0 = 不调用（默认）。你的算法自己决定何时建表，
*               比如在 image_init() 里自己调一次即可。
*           1 = 环境在开机初始化时自动调用一次 SCUT_PERSPECTIVE_INIT_FUNC。
*
*       如果你的算法用了 code\perspective.c 的逆透视，改成 1 最省事；
*       如果你的代码里根本没有逆透视（大多数情况），保持 0 即可，
*       环境不会去找这个函数，也就不会有链接错误。
*
* ★ 为什么默认 0：
*       别人的算法是多样化的 —— 有的用逆透视、有的不用。
*       如果默认就调用，没写这个函数的人会直接链接失败。
*       默认 0 + 需要的人显式打开，才能兼容所有写法。
********************************************************************************************************************/
#define SCUT_ENABLE_PERSPECTIVE_INIT    (0)                                     // 1=初始化时自动建逆透视表

/*********************************************************************************************************************
* 逆透视初始化函数名
* 说明：只有 SCUT_ENABLE_PERSPECTIVE_INIT 为 1 时才会用到。
*       默认指向 code\perspective.c 里提供的 ImagePerspective_Init()。
*       改名后这里跟着改即可。
********************************************************************************************************************/
#define SCUT_PERSPECTIVE_INIT_FUNC  ImagePerspective_Init                       // 逆透视建表函数名

